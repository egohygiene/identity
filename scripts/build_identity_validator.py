"""Bundle canonical validator modules into the existing standalone entry point."""

from __future__ import annotations

import argparse
import ast
from pathlib import Path
import sys
from typing import Sequence

ROOT = Path(__file__).resolve().parent
PACKAGE = ROOT / "identity_validation"
OUTPUT = ROOT / "validate_identity.py"
MODULES = (
    "common", "project", "tokens", "governance", "targets", "guidance",
    "voice", "usage", "handbook", "channels", "press_kit", "social_surfaces",
    "repository_presentation", "mascot", "entrypoint",
)
BANNER = "# Generated by scripts/build_identity_validator.py; edit scripts/identity_validation/*.py.\n"


def import_key(node: ast.Import | ast.ImportFrom) -> str:
    return ast.dump(node, include_attributes=False)


def source_block(path: Path, *, common: bool = False, prelude: set[str] | None = None) -> str:
    if path.is_symlink() or not path.is_file():
        raise ValueError(f"canonical validator module is missing or a symlink: {path.name}")
    source = path.read_text(encoding="utf-8")
    tree = ast.parse(source, filename=str(path))
    if common:
        if any(isinstance(node, ast.ImportFrom) and node.level for node in ast.walk(tree)):
            raise ValueError("the common standalone prelude cannot depend on package imports")
        return source.rstrip()
    lines = source.splitlines(keepends=True)
    blocks = []
    for index, node in enumerate(tree.body):
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            # The common module retains the original complete stdlib prelude.
            # Package imports are for focused internal-module use, never for
            # the dependency-free generated public script/Rust embed.
            if isinstance(node, ast.ImportFrom) and node.level:
                if node.level != 1 or node.module not in MODULES or any(alias.asname for alias in node.names):
                    raise ValueError(f"unsupported internal import in {path.name}")
            elif isinstance(node, ast.ImportFrom) and node.module == "__future__":
                if any(alias.name != "annotations" for alias in node.names):
                    raise ValueError("new future semantics require explicit standalone-prelude review")
            else:
                for alias in node.names:
                    single = ast.Import(names=[alias]) if isinstance(node, ast.Import) else ast.ImportFrom(module=node.module, names=[alias], level=0)
                    if import_key(single) not in (prelude or set()):
                        raise ValueError(f"add new standard-library import to common prelude before bundling {path.name}")
            continue
        if index == 0 and isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            continue
        decorators = getattr(node, "decorator_list", [])
        first = min([node.lineno] + [value.lineno for value in decorators]) - 1
        blocks.append("".join(lines[first:node.end_lineno]).rstrip())
    return "\n\n\n".join(blocks)


def render() -> str:
    common_tree = ast.parse((PACKAGE / "common.py").read_text(encoding="utf-8"))
    prelude = set()
    for node in common_tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            for alias in node.names:
                single = ast.Import(names=[alias]) if isinstance(node, ast.Import) else ast.ImportFrom(module=node.module, names=[alias], level=node.level)
                prelude.add(import_key(single))
    blocks = [source_block(PACKAGE / f"{name}.py", common=name == "common", prelude=prelude) for name in MODULES]
    source = "\n\n\n".join(blocks) + "\n"
    first, remaining = source.split("\n", 1)
    if not first.startswith("#!"):
        raise ValueError("canonical common source must retain the standalone shebang")
    source = first + "\n" + BANNER + remaining
    tree = ast.parse(source, filename=str(OUTPUT))
    if any(isinstance(node, ast.ImportFrom) and node.level for node in ast.walk(tree)):
        raise ValueError("generated standalone validator cannot contain relative imports")
    return source


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report drift without changing the standalone file.")
    args = parser.parse_args(argv)
    try:
        source = render()
        if args.check:
            if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != source:
                print("Standalone validator drift: run python3 scripts/build_identity_validator.py.", file=sys.stderr)
                return 1
            print("Standalone validator matches canonical modules; behavioral tests are separate.")
            return 0
        OUTPUT.write_text(source, encoding="utf-8")
        print(f"Generated {OUTPUT.name} from {len(MODULES)} canonical modules.")
        return 0
    except (OSError, SyntaxError, ValueError) as exc:
        print(f"Validator build: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
